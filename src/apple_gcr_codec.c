/** @brief 2-bit reverse `{0,2,1,3}`; involution used when packing low bits. */
static const uint8_t k_bit_reverse[4] = {0u, 2u, 1u, 3u};

uint8_t apple_gcr_encode_6n2(uint8_t six)
{
    return k_encode_6n2[(unsigned)six & APPLE_GCR_SIX_MASK];
}

uint8_t apple_gcr_decode_6n2(uint8_t disk)
{
    return k_decode_6n2[disk];
}

void apple_gcr_encode_4n4(uint8_t value, uint8_t *odd, uint8_t *even)
{
    if (odd != NULL)
    {
        *odd = (uint8_t)((uint8_t)(value >> 1) | 0xAAu);
    }
    if (even != NULL)
    {
        *even = (uint8_t)(value | 0xAAu);
    }
}

int apple_gcr_decode_4n4(uint8_t odd, uint8_t even, uint8_t *out)
{
    if (out == NULL)
    {
        return -1;
    }
    *out = (uint8_t)((uint8_t)((uint8_t)(odd << 1) | 1u) & even);
    return 0;
}

int apple_gcr_encode_sector(const uint8_t *restrict src, uint8_t *restrict dst)
{
    uint8_t buf[APPLE_GCR_NIBBLE_BYTES];
    size_t c = 0;

    if (src == NULL || dst == NULL)
    {
        return -1;
    }

    (void)memset(buf, 0, sizeof(buf));
    for (c = 0; c < 84u; ++c)
    {
        buf[c] = (uint8_t)(k_bit_reverse[src[c] & 3u] |
                           (uint8_t)(k_bit_reverse[src[c + 86u] & 3u] << 2) |
                           (uint8_t)(k_bit_reverse[src[c + 172u] & 3u] << 4));
    }
    buf[84] = (uint8_t)(k_bit_reverse[src[84] & 3u] |
                        (uint8_t)(k_bit_reverse[src[170] & 3u] << 2));
    buf[85] = (uint8_t)(k_bit_reverse[src[85] & 3u] |
                        (uint8_t)(k_bit_reverse[src[171] & 3u] << 2));
    for (c = 0; c < APPLE_GCR_SECTOR_BYTES; ++c)
    {
        buf[86u + c] = (uint8_t)(src[c] >> 2);
    }
    buf[342] = buf[341];
    for (c = 341u; c > 0u; --c)
    {
        buf[c] = (uint8_t)(buf[c] ^ buf[c - 1u]);
    }
    for (c = 0; c < APPLE_GCR_NIBBLE_BYTES; ++c)
    {
        dst[c] = apple_gcr_encode_6n2(buf[c]);
    }
    return 0;
}

int apple_gcr_decode_sector(const uint8_t *restrict src, uint8_t *restrict dst)
{
    uint8_t buf[APPLE_GCR_NIBBLE_BYTES];
    uint8_t last = 0;
    size_t c = 0;

    if (src == NULL || dst == NULL)
    {
        return -1;
    }

    for (c = 0; c < APPLE_GCR_NIBBLE_BYTES; ++c)
    {
        const uint8_t v = apple_gcr_decode_6n2(src[c]);
        if (v == APPLE_GCR_INVALID)
        {
            return -1;
        }
        buf[c] = v;
    }
    for (c = 0; c < 342u; ++c)
    {
        last = (uint8_t)(buf[c] ^ last);
        buf[c] = last;
    }
    if (buf[342] != last)
    {
        return -1;
    }

    (void)memset(dst, 0, APPLE_GCR_SECTOR_BYTES);
    for (c = 0; c < 84u; ++c)
    {
        dst[c] = k_bit_reverse[buf[c] & 3u];
        dst[c + 86u] = k_bit_reverse[(buf[c] >> 2) & 3u];
        dst[c + 172u] = k_bit_reverse[(buf[c] >> 4) & 3u];
    }
    dst[84] = k_bit_reverse[buf[84] & 3u];
    dst[170] = k_bit_reverse[(buf[84] >> 2) & 3u];
    dst[85] = k_bit_reverse[buf[85] & 3u];
    dst[171] = k_bit_reverse[(buf[85] >> 2) & 3u];
    for (c = 0; c < APPLE_GCR_SECTOR_BYTES; ++c)
    {
        dst[c] = (uint8_t)((uint8_t)(buf[86u + c] << 2) | (uint8_t)(dst[c] & 3u));
    }
    return 0;
}
